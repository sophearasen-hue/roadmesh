//! The Step 4 simulation report (BUILD_PLAN Step 4): runs the city traffic matrix
//! and writes a plain-language Markdown report (`roadmesh-sim report`).

use std::fmt::Write as _;
use std::sync::Mutex;

use crate::city::{CONFLICT_TTC_S, CRITICAL_TTC_S, City, CityOptions, CityStats, GRACE_S};

/// GPS quality bands: (label, range of each phone's error in m).
pub const GPS_BANDS: [(&str, (f64, f64)); 3] = [
    ("good (2–4 m)", (2.0, 4.0)),
    ("mixed (2–10 m)", (2.0, 10.0)),
    ("poor (6–10 m)", (6.0, 10.0)),
];
/// Vehicle counts.
pub const VEHICLES: [usize; 3] = [40, 80, 120];
/// Packet loss levels.
pub const LOSSES: [f64; 3] = [0.0, 0.2, 0.4];

/// Run many cities in parallel; results in input order.
pub fn run_all(cases: Vec<CityOptions>, threads: usize) -> Vec<CityStats> {
    let n = cases.len();
    let slots: Mutex<Vec<Option<CityStats>>> = Mutex::new(vec![None; n]);
    let next = Mutex::new(0usize);
    std::thread::scope(|sc| {
        for _ in 0..threads.max(1) {
            sc.spawn(|| {
                loop {
                    let i = {
                        let Ok(mut g) = next.lock() else { return };
                        let i = *g;
                        *g += 1;
                        i
                    };
                    let Some(opts) = cases.get(i).cloned() else {
                        return;
                    };
                    let s = City::new(opts).run();
                    if let Ok(mut g) = slots.lock() {
                        g[i] = Some(s);
                    }
                }
            });
        }
    });
    slots
        .into_inner()
        .unwrap_or_default()
        .into_iter()
        .map(Option::unwrap_or_default)
        .collect()
}

fn pct(a: u64, b: u64) -> String {
    if b == 0 {
        "–".into()
    } else {
        format!("{:.1} %", 100.0 * a as f64 / b as f64)
    }
}

fn merged<'a>(it: impl Iterator<Item = &'a CityStats>) -> CityStats {
    let mut m = CityStats::default();
    for s in it {
        m.merge(s);
    }
    m
}

/// Build the report. `seeds` runs per setting, each `duration_s` long.
pub fn build(seeds: u64, duration_s: f64, threads: usize) -> String {
    let base = |v: usize, loss: f64, gps: (f64, f64), seed: u64| CityOptions {
        vehicles: v,
        loss,
        gps_m: gps,
        seed,
        duration_s,
        ..CityOptions::default()
    };
    // 1. the matrix
    let mut cases = Vec::new();
    let mut keys = Vec::new();
    for (bi, band) in GPS_BANDS.iter().enumerate() {
        for &v in &VEHICLES {
            for &loss in &LOSSES {
                for seed in 1..=seeds {
                    cases.push(base(v, loss, band.1, seed));
                    keys.push((bi, v, loss));
                }
            }
        }
    }
    // 2. adoption: 80 vehicles, 20 % loss, mixed GPS
    let pens = [1.0, 0.5, 0.2, 0.0];
    let first_pen = cases.len();
    for &p in &pens {
        for seed in 1..=seeds {
            cases.push(CityOptions {
                penetration: p,
                ..base(80, 0.2, GPS_BANDS[1].1, seed)
            });
        }
    }
    // 3. the security check: real signatures on vs off, same seeds
    let first_sec = cases.len();
    for security in [false, true] {
        for seed in 1..=seeds {
            cases.push(CityOptions {
                security,
                ..base(40, 0.0, GPS_BANDS[0].1, seed)
            });
        }
    }
    let results = run_all(cases, threads);
    let matrix = &results[..first_pen];
    let adoption = &results[first_pen..first_sec];
    let sec = &results[first_sec..];

    let all = merged(matrix.iter());
    let (mean, median) = all.lead();
    let mut r = String::new();
    let _ = writeln!(r, "# RoadMesh simulation report (Step 4)\n");
    let _ = writeln!(
        r,
        "Generated by `roadmesh-sim report --seeds {seeds} --duration {duration_s:.0}`. The \
         simulated city is the phone prototype's grid in Phnom Penh: 2.4 × 1.6 km, 6 roads \
         (40/60/40 km/h), unsignalised junctions with buildings at the corners, 55 % \
         motorbikes, 30 % cars, 8 % tuk-tuks, 7 % trucks, and calm (30 %), normal (50 %) and \
         aggressive (20 %) drivers. {} runs of {duration_s:.0} s; {:.0} km driven by app users.\n",
        matrix.len(),
        all.app_km
    );
    let _ = writeln!(r, "## Summary\n");
    let _ = writeln!(r, "| | Result | Target |");
    let _ = writeln!(r, "|---|---|---|");
    let tn = all.gated_conflicts - all.gated_turn_conflicts;
    let tm = all.gated_missed - all.gated_turn_missed;
    let _ = writeln!(
        r,
        "| **Missed conflicts**, both phones within the GPS confidence gate (8 m), not counting turns that had not started | **{}** ({tm} of {tn}) | under 2 % |",
        pct(tm, tn)
    );
    let _ = writeln!(
        r,
        "| ... turns that had not started yet (no phone can know a turn before it begins) | {} ({} of {}) | reported separately |",
        pct(all.gated_turn_missed, all.gated_turn_conflicts),
        all.gated_turn_missed,
        all.gated_turn_conflicts
    );
    let _ = writeln!(
        r,
        "| Missed conflicts, both phones within the gate, all | {} ({} of {}) | – |",
        pct(all.gated_missed, all.gated_conflicts),
        all.gated_missed,
        all.gated_conflicts
    );
    let _ = writeln!(
        r,
        "| Missed conflicts, all pairs | {} ({} of {}) | – |",
        pct(all.missed, all.conflicts),
        all.missed,
        all.conflicts
    );
    let _ = writeln!(
        r,
        "| Missed conflicts involving a motorbike | {} ({} of {}) | – |",
        pct(all.moto_missed, all.moto_conflicts),
        all.moto_missed,
        all.moto_conflicts
    );
    let _ = writeln!(
        r,
        "| Warning time before the predicted touch | mean {mean:.1} s, median {median:.1} s | – |"
    );
    let _ = writeln!(
        r,
        "| False Danger alerts per 100 km | **{:.0}** | under 1 (SPEC §8) |",
        all.false_danger_per_100km()
    );
    let _ = writeln!(
        r,
        "| Honest vehicles wrongly blocked as misbehaving | {} | 0 |",
        all.honest_blocked
    );
    let pen = |k: usize| merged(adoption[k * seeds as usize..(k + 1) * seeds as usize].iter());
    let (with, without) = (pen(0), pen(3));
    let crashes = |s: &CityStats| s.collisions.iter().sum::<u64>();
    let _ = writeln!(
        r,
        "| Crashes, everyone has the app vs nobody (80 vehicles, 20 % loss, mixed GPS) | {} vs {} | fewer |\n",
        crashes(&with),
        crashes(&without)
    );

    let _ = writeln!(r, "## How it is measured\n");
    let _ = writeln!(
        r,
        "* **Conflict:** using the vehicles' true positions and their real planned routes \
         (including the turn each driver has decided on), with nobody reacting, two outlines \
         would touch within {CONFLICT_TTC_S:.0} s. Only pairs where both have the app count, \
         because a phone can only warn about vehicles that broadcast.\n\
         * **Warned in time:** either phone showed a Warning or Danger about the other before \
         the predicted touch came closer than {CRITICAL_TTC_S:.1} s (allowing {GRACE_S:.1} s \
         for radio and processing; an alert shown in the last second counts). Otherwise the \
         conflict is **missed**.\n\
         * **False alarm:** a Warning or Danger about another vehicle when, with true positions \
         and no reaction, the two would never come within 1 m of each other in the next 8 s.\n\
         * **GPS confidence gate:** SPEC §6 allows only a Caution for vehicles whose phone \
         reports worse than 8 m accuracy, so those pairs are shown separately.\n\
         * The phones run the real Rust core (spec profile) with GPS smoothing and map \
         matching. Drivers with the app react to a Warning or Danger after 1 s and follow \
         the braking advice. Signature checks are off in these runs to keep them fast; the \
         check at the end shows they change nothing.\n"
    );

    let _ = writeln!(r, "## Results by traffic, radio and GPS\n");
    let _ = writeln!(
        r,
        "| GPS | Vehicles | Packet loss | Conflicts | Missed (target) | Missed (all) | False Danger / 100 km | Mean warning time |"
    );
    let _ = writeln!(r, "|---|---:|---:|---:|---:|---:|---:|---:|");
    let mut i = 0;
    while i < matrix.len() {
        let (bi, v, loss) = keys[i];
        let j = (i..matrix.len())
            .find(|&k| keys[k] != keys[i])
            .unwrap_or(matrix.len());
        let m = merged(matrix[i..j].iter());
        let _ = writeln!(
            r,
            "| {} | {v} | {:.0} % | {} | {} | {} | {:.0} | {:.1} s |",
            GPS_BANDS[bi].0,
            loss * 100.0,
            m.conflicts,
            pct(
                m.gated_missed - m.gated_turn_missed,
                m.gated_conflicts - m.gated_turn_conflicts
            ),
            pct(m.missed, m.conflicts),
            m.false_danger_per_100km(),
            m.lead().0
        );
        i = j;
    }
    let _ = writeln!(r);

    let _ = writeln!(r, "## Why conflicts were missed\n");
    let causes = [
        "The two phones never heard each other (range, buildings, packet loss)",
        "A phone's GPS was worse than the 8 m gate (Caution only, by design)",
        "A driver was about to turn and had not started yet (a phone cannot know)",
        "Other: detection or alert logic",
    ];
    let _ = writeln!(r, "| Cause | Missed | Share of all conflicts |");
    let _ = writeln!(r, "|---|---:|---:|");
    for (k, c) in causes.iter().enumerate() {
        let _ = writeln!(
            r,
            "| {c} | {} | {} |",
            all.miss_causes[k],
            pct(all.miss_causes[k], all.conflicts)
        );
    }
    let _ = writeln!(
        r,
        "\n{} of the missed conflicts showed a Caution \"possible conflict, ease off\" instead.\n",
        all.missed_with_caution
    );

    let _ = writeln!(r, "## False alarms by alert\n");
    let _ = writeln!(r, "| Alert | Shown | False | False Danger per 100 km |");
    let _ = writeln!(r, "|---|---:|---:|---:|");
    for (k, (n, f, fd)) in &all.by_kind {
        let _ = writeln!(
            r,
            "| {k} | {n} | {} | {:.0} |",
            pct(*f, *n),
            *fd as f64 * 100.0 / all.app_km.max(1e-9)
        );
    }
    let _ = writeln!(r);

    let _ = writeln!(r, "## When only some drivers have the app\n");
    let _ = writeln!(
        r,
        "80 vehicles, 20 % packet loss, mixed GPS, {seeds} runs each.\n"
    );
    let _ = writeln!(
        r,
        "| Drivers with the app | Crashes | Conflicts between app users | Missed (gate) |"
    );
    let _ = writeln!(r, "|---:|---:|---:|---:|");
    for (k, p) in pens.iter().enumerate() {
        let m = pen(k);
        let _ = writeln!(
            r,
            "| {:.0} % | {} | {} | {} |",
            p * 100.0,
            crashes(&m),
            m.conflicts,
            pct(m.gated_missed, m.gated_conflicts)
        );
    }
    let _ = writeln!(r);

    let _ = writeln!(r, "## Signature check\n");
    let k = seeds as usize;
    let (off, on) = (merged(sec[..k].iter()), merged(sec[k..].iter()));
    let _ = writeln!(
        r,
        "40 vehicles, good GPS, no loss, {seeds} runs each, with signature checks off and with \
         real ECDSA P-256 certificates on every phone. The traffic is not identical (a new \
         vehicle is trusted only once its full certificate arrives, up to 1 s), so compare \
         the rates.\n"
    );
    let _ = writeln!(r, "| | Checks off | Checks on |");
    let _ = writeln!(r, "|---|---:|---:|");
    let _ = writeln!(
        r,
        "| Missed conflicts | {} | {} |",
        pct(off.missed, off.conflicts),
        pct(on.missed, on.conflicts)
    );
    let _ = writeln!(
        r,
        "| False Danger per 100 km | {:.0} | {:.0} |",
        off.false_danger_per_100km(),
        on.false_danger_per_100km()
    );
    let _ = writeln!(r, "| Crashes | {} | {} |", crashes(&off), crashes(&on));
    let _ = writeln!(
        r,
        "| Honest vehicles blocked | {} | {} |\n",
        off.honest_blocked, on.honest_blocked
    );

    let _ = writeln!(r, "## Limits of this simulation\n");
    let _ = writeln!(
        r,
        "* The radio is a simple model (150 m in sight, 60 m around buildings, random loss); \
         Step 5 replaces it with field measurements.\n\
         * Relaying is off: the full relay rules arrive in Step 7.\n\
         * GPS error drifts slowly (30 s) like real phones, plus a little jitter.\n\
         * Drivers follow simple rules; real Cambodian traffic (motorbikes filtering between \
         lanes, wrong-way riders) is more varied.\n\
         * The ground truth uses the same kind of motion model as the core for the 3 s window; \
         crashes in the simulation do not depend on it.\n"
    );
    r
}
